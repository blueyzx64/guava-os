# Build stylesheet.css from styles/base.css and every features/<name>/style.css (name order,
# C locale). stylesheet.css is committed so `gnome-extensions pack`, `make install` and EGO
# keep working from a plain checkout; `make css-check` fails when it is out of date.
#   tools/build-css.sh            write stylesheet.css
#   tools/build-css.sh --check    exit 1 if stylesheet.css differs from a fresh build
set -euo pipefail
cd "$(dirname "$0")/.."
build() {
    printf '/* Generated by tools/build-css.sh from styles/base.css and features/*/style.css.\n   Do not edit: change those files and run `make css`. */\n'
    for f in styles/base.css $(LC_ALL=C ls features/*/style.css); do
        printf '\n/* ==== %s ==== */\n\n' "$f"
        cat "$f"
    done
}
if [ "${1:-}" = --check ]; then
    if ! diff -q <(build) stylesheet.css >/dev/null; then
        echo 'stylesheet.css is out of date: run `make css` and commit it' >&2
        exit 1
    fi
    echo 'stylesheet.css is up to date'
else
    build > stylesheet.css
fi
